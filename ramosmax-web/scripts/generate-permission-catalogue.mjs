#!/usr/bin/env node
/**
 * Generates the RamosMAX permission catalogue for the web application from the
 * Phase 9 Flutter/Firebase reference implementation.
 *
 * Sources (read-only, never modified):
 *   ../functions/src/access_catalog.json   - server-authoritative keys, roles, ranks
 *   ../lib/core/auth/permissions.dart      - human labels and group prefixes
 *
 * Emits:
 *   src/lib/permissions/catalogue.generated.ts
 *   ../supabase/migrations/0002_permission_catalogue.sql
 *
 * Run `npm run gen:permissions` to regenerate; `npm run test` fails if the
 * committed output no longer matches the reference implementation. This is the
 * web replacement for the Dart/rules/catalogue three-way drift test.
 */
import { readFileSync, writeFileSync, mkdirSync } from 'node:fs';
import { dirname, join, resolve } from 'node:path';
import { fileURLToPath } from 'node:url';

const here = dirname(fileURLToPath(import.meta.url));
const webRoot = resolve(here, '..');
const repoRoot = resolve(webRoot, '..');

const catalog = JSON.parse(
  readFileSync(join(repoRoot, 'functions/src/access_catalog.json'), 'utf8'),
);
const dart = readFileSync(join(repoRoot, 'lib/core/auth/permissions.dart'), 'utf8');

// --- labels from the Dart enum -------------------------------------------
// Entries look like:  usersView('users.view', 'View users'),
// and occasionally use double quotes:  attendanceRecord('attendance.record', "Record other staff's attendance"),
const labels = new Map();
const ENTRY = /^\s{2}[a-zA-Z][a-zA-Z0-9]*\(\s*'([^']+)'\s*,\s*(?:'([^']*)'|"([^"]*)")\s*\)/gm;
for (const m of dart.matchAll(ENTRY)) {
  labels.set(m[1], m[2] ?? m[3]);
}

// --- groups from PermissionGroup ------------------------------------------
// Entries look like:  users('Users', ['users.']),
const groups = [];
const GROUP = /^\s{2}([a-zA-Z]+)\(\s*'([^']+)'\s*,\s*\[([^\]]*)\]\s*\)/gm;
const groupBody = dart.slice(dart.indexOf('enum PermissionGroup'));
for (const m of groupBody.matchAll(GROUP)) {
  const prefixes = [...m[3].matchAll(/'([^']+)'/g)].map((p) => p[1]);
  groups.push({ id: m[1], label: m[2], prefixes });
}
const groupOf = (key) =>
  groups.find((g) => g.prefixes.some((p) => key.startsWith(p)))?.id ?? 'system';

// --- consistency checks against the reference ------------------------------
const permissions = [...catalog.permissions];
const problems = [];
for (const key of permissions) {
  if (!labels.has(key)) problems.push(`no label in permissions.dart for "${key}"`);
}
for (const key of labels.keys()) {
  if (!permissions.includes(key))
    problems.push(`permissions.dart has "${key}" which access_catalog.json does not`);
}
if (groups.length === 0) problems.push('failed to parse PermissionGroup from permissions.dart');
if (problems.length) {
  console.error('Permission catalogue is inconsistent with the reference implementation:');
  for (const p of problems) console.error('  - ' + p);
  process.exit(1);
}

const roles = Object.keys(catalog.roles);
const adminOnly = [...catalog.adminOnlyPermissions].sort();
const authorizationOnly = [...(catalog.authorizationOnlyPermissions ?? [])].sort();
const sq = (s) => `'${String(s).replace(/'/g, "''")}'`; // SQL literal
const tq = (s) => JSON.stringify(s); // TS literal

// --- TypeScript ------------------------------------------------------------
const ts = `// AUTO-GENERATED — DO NOT EDIT BY HAND.
// Generated by scripts/generate-permission-catalogue.mjs from the Phase 9
// reference implementation (functions/src/access_catalog.json +
// lib/core/auth/permissions.dart). Run \`npm run gen:permissions\` to refresh.
//
// Client-side permission checks drive what the UI shows. They are NOT a
// security boundary — RLS and the SECURITY DEFINER functions are.

export const PERMISSIONS = [
${permissions.map((p) => `  ${tq(p)},`).join('\n')}
] as const;

export type Permission = (typeof PERMISSIONS)[number];

export const ROLES = [
${roles.map((r) => `  ${tq(r)},`).join('\n')}
] as const;

export type Role = (typeof ROLES)[number];

/** Rank governs who may administer or assign whom. Higher outranks lower. */
export const ROLE_RANKS: Record<Role, number> = ${JSON.stringify(catalog.roleRanks, null, 2)};

export const PERMISSION_LABELS: Record<Permission, string> = {
${permissions.map((p) => `  ${tq(p)}: ${tq(labels.get(p))},`).join('\n')}
};

export const PERMISSION_GROUPS = [
${groups.map((g) => `  { id: ${tq(g.id)}, label: ${tq(g.label)}, prefixes: ${JSON.stringify(g.prefixes)} },`).join('\n')}
] as const;

export type PermissionGroupId = (typeof PERMISSION_GROUPS)[number]['id'];

export const PERMISSION_GROUP_OF: Record<Permission, PermissionGroupId> = {
${permissions.map((p) => `  ${tq(p)}: ${tq(groupOf(p))},`).join('\n')}
};

/** Admin holds every permission; hasPermission() short-circuits on role. */
export const ROLE_PERMISSIONS: Record<Role, readonly Permission[] | '*'> = {
${roles
  .map((r) =>
    catalog.roles[r] === '*'
      ? `  ${tq(r)}: '*',`
      : `  ${tq(r)}: [\n${[...catalog.roles[r]]
          .sort()
          .map((p) => `    ${tq(p)},`)
          .join('\n')}\n  ],`,
  )
  .join('\n')}
};

/** Only an Administrator may grant, deny or hand these out temporarily. */
export const ADMIN_ONLY_PERMISSIONS: readonly Permission[] = [
${adminOnly.map((p) => `  ${tq(p)},`).join('\n')}
];

/**
 * Exist only inside an after-hours authorisation window. Never granted
 * permanently, never through the generic temporary-access editor.
 */
export const AUTHORIZATION_ONLY_PERMISSIONS: readonly Permission[] = [
${authorizationOnly.map((p) => `  ${tq(p)},`).join('\n')}
];

/** Roles whose passwords a non-admin holding users.passwords.reset may reset. */
export const PASSWORD_RESET_ROLES_FOR_NON_ADMINS: readonly Role[] = ${JSON.stringify(
  catalog.passwordResetRolesForNonAdmins,
)};

export const SPECIALIZATIONS: readonly string[] = ${JSON.stringify(catalog.specializations)};

/** Longest temporary grant anyone may hand out (30 days), as in access.js. */
export const MAX_TEMPORARY_MS = 30 * 24 * 3600_000;
`;

const tsPath = join(webRoot, 'src/lib/permissions/catalogue.generated.ts');
mkdirSync(dirname(tsPath), { recursive: true });
writeFileSync(tsPath, ts);

// --- SQL seed --------------------------------------------------------------
const sql = `-- AUTO-GENERATED — DO NOT EDIT BY HAND.
-- Generated by ramosmax-web/scripts/generate-permission-catalogue.mjs from the
-- Phase 9 reference implementation. Run \`npm run gen:permissions\` to refresh.
--
-- The database is the single source of truth for the permission catalogue;
-- TypeScript types are generated from the same source, so the UI cannot
-- reference a permission that does not exist.
--
-- Idempotent and non-destructive: re-running it updates labels and flags and
-- re-syncs role defaults. It never drops a table and never touches a user's
-- individual grants or denials.

begin;

-- ---------------------------------------------------------------------------
-- Permission groups (display order follows the Flutter PermissionGroup enum)
-- ---------------------------------------------------------------------------
-- Groups are seeded FIRST: app.permissions.group_id references them.

insert into app.permission_groups (id, label, sort_order) values
${groups.map((g, i) => `  (${sq(g.id)}, ${sq(g.label)}, ${i + 1})`).join(',\n')}
on conflict (id) do update
  set label = excluded.label, sort_order = excluded.sort_order;

-- ---------------------------------------------------------------------------
-- Permission catalogue
-- ---------------------------------------------------------------------------

insert into app.permissions (key, label, group_id, is_admin_only, is_authorization_only) values
${permissions
  .map(
    (p) =>
      `  (${sq(p)}, ${sq(labels.get(p))}, ${sq(groupOf(p))}, ${adminOnly.includes(p)}, ${authorizationOnly.includes(p)})`,
  )
  .join(',\n')}
on conflict (key) do update
  set label                 = excluded.label,
      group_id              = excluded.group_id,
      is_admin_only         = excluded.is_admin_only,
      is_authorization_only = excluded.is_authorization_only;

-- ---------------------------------------------------------------------------
-- Roles and ranks
-- ---------------------------------------------------------------------------

insert into app.roles (id, rank, grants_all) values
${roles
  .map((r) => `  (${sq(r)}, ${catalog.roleRanks[r]}, ${catalog.roles[r] === '*'})`)
  .join(',\n')}
on conflict (id) do update
  set rank = excluded.rank, grants_all = excluded.grants_all;

-- ---------------------------------------------------------------------------
-- Role -> permission defaults
-- ---------------------------------------------------------------------------
-- Admin is grants_all and deliberately has no rows here: app.has_permission()
-- short-circuits on the admin role, exactly as hasPermission() does in
-- firebase/firestore.rules. Re-seeding replaces the defaults wholesale so a
-- permission removed from a role upstream is removed here too.

delete from app.role_permissions
 where role_id in (${roles
   .filter((r) => catalog.roles[r] !== '*')
   .map(sq)
   .join(', ')});

insert into app.role_permissions (role_id, permission_key) values
${roles
  .filter((r) => catalog.roles[r] !== '*')
  .flatMap((r) => [...catalog.roles[r]].sort().map((p) => `  (${sq(r)}, ${sq(p)})`))
  .join(',\n')}
on conflict do nothing;

-- ---------------------------------------------------------------------------
-- Roles whose passwords a non-admin may reset (access.js
-- PASSWORD_RESET_ROLES_FOR_NON_ADMINS). By default: Workers only — NOT
-- Cashiers, even though Cashiers rank below Managers.
-- ---------------------------------------------------------------------------

update app.roles set password_resettable_by_non_admin = (id in (${catalog.passwordResetRolesForNonAdmins
  .map(sq)
  .join(', ')}));

commit;
`;

const sqlPath = join(webRoot, 'supabase/migrations/0002_permission_catalogue.sql');
mkdirSync(dirname(sqlPath), { recursive: true });
writeFileSync(sqlPath, sql);

console.log(`Generated from the Phase 9 reference implementation:`);
console.log(`  ${permissions.length} permissions, ${groups.length} groups, ${roles.length} roles`);
console.log(`  admin-only: ${adminOnly.length}, authorization-only: ${authorizationOnly.length}`);
console.log(`  -> src/lib/permissions/catalogue.generated.ts`);
console.log(`  -> supabase/migrations/0002_permission_catalogue.sql`);
